package nebula.lang

import nebula.core.NodeTypes

data class Diag(val file: String, val line: Int, val message: String) {
    override fun toString() = "$file:$line: $message"
}
data class TweakMeta(val name: String, val kind: String, val default: String)   // kind: Int Float Bool String
data class BroadcastMeta(val name: String, val params: List<Pair<String, String>>)
data class ScriptMeta(
    val name: String, val base: String, val file: String,
    val tweaks: List<TweakMeta>, val ticks: List<Int>, val everyMs: List<Int>, val frame: Boolean,
    val broadcasts: List<BroadcastMeta>,
    /** DynamicBar scripts: node paths (relative to the bar, `^` already turned into `..`) of the empty-bar and full-bar sprites, "" when not declared. */
    val barEmpty: String = "", val barFull: String = "",
)
data class ScriptSource(val path: String, val text: String)
data class Origin(val file: String, val line: Int)
class Lowered(val source: String, val metas: List<ScriptMeta>, val diags: List<Diag>, val origins: List<Origin>) {
    val ok get() = diags.isEmpty()
    /** Rewrites `game.sn:LINE:COL` in compiler output to the original script file and line. */
    fun remap(compilerOutput: String): String {
        val mapped = Regex("""game\.sn:(\d+)""").replace(compilerOutput) { m ->
            val o = origins.getOrNull(m.groupValues[1].toInt() - 1)
            if (o != null && o.line > 0) "${o.file}:${o.line}" else m.value
        }
        val names = Regex("""undefined variable '(\w+)'""").findAll(mapped).map { it.groupValues[1] }.distinct().toList()
        if (names.isEmpty()) return mapped
        return mapped + "\nhint: a variable declared inside a function (or an if / for block) only exists there. To use '" + names.joinToString("', '") +
            "' in other functions too, declare it at the top of the script, one tab in (next to your tweaks), and assign it inside the function."
    }
}

/**
 * Lowers Nebula scripts (.nbs) to one plain SuperNova file (game.sn).
 * Nebula adds these forms on top of SuperNova (see docs/GUIDE.md):
 *   script Name of Base:          tweak x = 1            broadcast hit(n: Int)     shout hit(3)
 *   fn onHear(hit, n):            fn onHear(@Path.hit, n):     fn onHear(@Path as Type.hit, n):
 *   fn onTick(30):  fn onEvery(2.5):  fn onFrame():       @Path  @A/B  @^  @/Abs   as Type
 *   spawn "a.nscn" under @Parent      wait 1.5
 */
object Transpiler {
    private val headerRe = Regex("""^script\s+([A-Za-z_]\w*)(?:\s+of\s+([A-Za-z_]\w*))?\s*:\s*$""")
    private val reserved = NodeTypes.scriptClassNames + setOf("Bc0", "BcNode", "BcPoint", "BcFloat", "Vec2")

    private class Script(val src: ScriptSource, val name: String, val base: String, val headerLine: Int,
                         val body: List<Pair<Int, String>>, val extras: List<Pair<Int, String>>, val uses: List<String>)

    private class Out {
        val lines = ArrayList<String>(); val origins = ArrayList<Origin>()
        fun add(text: String, file: String = "<generated>", line: Int = 0) { lines.add(text); origins.add(Origin(file, line)) }
    }

    fun lower(sources: List<ScriptSource>): Lowered {
        val diags = ArrayList<Diag>()
        val scripts = ArrayList<Script>()
        for (s in sources) parseFile(s, diags)?.let { scripts.add(it) }
        val names = HashSet<String>()
        for (s in scripts) {
            if (s.name in reserved) diags.add(Diag(s.src.path, s.headerLine, "'${s.name}' is a built-in name"))
            if (!names.add(s.name)) diags.add(Diag(s.src.path, s.headerLine, "script '${s.name}' is defined twice"))
        }
        val byName = scripts.associateBy { it.name }
        for (s in scripts) if (!NodeTypes.exists(s.base) && s.base !in byName)
            diags.add(Diag(s.src.path, s.headerLine, "unknown base '${s.base}' (a node type or another script)"))

        // dependency order: a base script must come before the scripts that extend it
        val ordered = ArrayList<Script>(); val state = HashMap<String, Int>()
        fun visit(s: Script) {
            val st = state[s.name]
            if (st == 2) return
            if (st == 1) { diags.add(Diag(s.src.path, s.headerLine, "script '${s.name}' extends itself")); return }
            state[s.name] = 1
            byName[s.base]?.let { visit(it) }
            state[s.name] = 2; ordered.add(s)
        }
        scripts.forEach { visit(it) }

        val metas = HashMap<String, ScriptMeta>()
        val infos = HashMap<String, Info>()
        for (s in ordered) { val info = scan(s, diags); infos[s.name] = info; metas[s.name] = info.meta }

        val out = Out()
        out.add("# Generated by Nebula from your scripts. Do not edit: edit the .nbs files instead.")
        out.add("use nebula")
        val uses = ordered.flatMap { it.uses }.distinct()
        for (u in uses) out.add(u)
        for (s in ordered) emit(s, infos[s.name]!!, metas, out, diags)

        out.add("")
        out.add("# ---- entry points (bare names; snc mangles exports of imported modules) ----")
        out.add("export fn nbAttach(id: Int, script: String):")
        out.add("\tmatch script:")
        out.add("\t\tcase \"\":")
        out.add("\t\t\tpass")
        ordered.forEachIndexed { i, s -> out.add("\t\tcase \"${s.name}\":"); out.add("\t\t\tvar made$i = ${s.name}(id)") }
        for ((fn, params, call) in listOf(
            Triple("nbReady", "id: Int", "id"), Triple("nbFrame", "id: Int, delta: Float", "id, delta"),
            Triple("nbTick", "id: Int, rate: Int, delta: Float", "id, rate, delta"),
            Triple("nbEvery", "id: Int, ms: Int, delta: Float", "id, ms, delta"),
            Triple("nbFire", "id: Int, name: String, a: Float, b: Float, other: Int", "id, name, a, b, other"),
            Triple("nbFreed", "id: Int", "id"))) {
            out.add("export fn $fn($params):"); out.add("\tnebula.$fn($call)")
        }
        return Lowered(out.lines.joinToString("\n") + "\n", ordered.map { metas[it.name]!! }, diags, out.origins)
    }

    // ---------------------------------------------------------------- parsing
    private fun parseFile(s: ScriptSource, diags: MutableList<Diag>): Script? {
        val lines = s.text.lines()
        val uses = ArrayList<String>()
        var idx = 0
        while (idx < lines.size) {
            val t = lines[idx].trim()
            if (t.isEmpty() || t.startsWith("#")) { idx++; continue }
            if (t.startsWith("use ")) { uses.add(t); idx++; continue }
            break
        }
        if (idx >= lines.size) { diags.add(Diag(s.path, 1, "empty script: expected 'script Name of Base:'")); return null }
        val m = headerRe.matchEntire(stripComment(lines[idx]).trim())
        if (m == null) { diags.add(Diag(s.path, idx + 1, "expected 'script Name of Base:' (for example: script Player of Body:)")); return null }
        val body = ArrayList<Pair<Int, String>>(); val extras = ArrayList<Pair<Int, String>>()
        var inBody = true
        for (i in idx + 1 until lines.size) {
            val l = lines[i]
            if (inBody && l.isNotBlank() && !l.startsWith("\t") && !l.startsWith(" ") && !l.trimStart().startsWith("#")) inBody = false
            if (inBody) body.add(i + 1 to l) else extras.add(i + 1 to l)
        }
        return Script(s, m.groupValues[1], m.groupValues[2].ifEmpty { "Node2D" }, idx + 1, body, extras, uses)
    }

    private fun stripComment(l: String): String { val i = commentStart(l); return if (i < 0) l else l.substring(0, i) }
    private fun commentStart(l: String): Int {
        var inStr = false; var i = 0
        while (i < l.length) {
            val c = l[i]
            if (inStr) { if (c == '\\') i++ else if (c == '"') inStr = false } else if (c == '"') inStr = true else if (c == '#') return i
            i++
        }
        return -1
    }

    // ---------------------------------------------------------------- scanning (meta)
    private class Info(val meta: ScriptMeta, val methodParams: Map<String, Int>)

    private val tweakRe = Regex("""^tweak\s+([A-Za-z_]\w*)\s*(?::\s*(\w+))?\s*=\s*(.+)$""")
    private val bcRe = Regex("""^broadcast\s+([A-Za-z_]\w*)\s*(?:\((.*)\))?\s*$""")
    private val tickRe = Regex("""^fn\s+onTick\s*\(\s*(\d+)\s*\)\s*:\s*$""")
    private val everyRe = Regex("""^fn\s+onEvery\s*\(\s*(\d+(?:\.\d+)?)\s*\)\s*:\s*$""")
    private val frameRe = Regex("""^fn\s+onFrame\s*\(\s*([A-Za-z_]\w*)?\s*\)\s*:\s*$""")
    /** `empty @Back` / `full @Fill`: which child Sprite is the empty bar and which the full bar of a DynamicBar script. */
    private val barRe = Regex("""^(empty|full)\s+@([^\s@]+)$""")

    private fun scan(s: Script, diags: MutableList<Diag>): Info {
        val tweaks = ArrayList<TweakMeta>(); val ticks = ArrayList<Int>(); val every = ArrayList<Int>()
        val bcs = ArrayList<BroadcastMeta>(); var frame = false
        var barEmpty = ""; var barFull = ""
        val methodParams = HashMap<String, Int>()
        for ((ln, raw) in s.body) {
            val t = stripComment(raw).trim()
            Regex("""^(?:async\s+)?fn\s+([A-Za-z_]\w*)\s*\((.*)\)""").find(t)?.let { m ->
                methodParams[m.groupValues[1]] = if (m.groupValues[2].isBlank()) 0 else m.groupValues[2].split(',').size
            }
            tweakRe.matchEntire(t)?.let { m ->
                val ty = m.groupValues[2].ifEmpty { inferKind(m.groupValues[3]) }
                if (ty !in listOf("Int", "Float", "Bool", "String")) diags.add(Diag(s.src.path, ln, "tweak '${m.groupValues[1]}' must be Int, Float, Bool or String"))
                else tweaks.add(TweakMeta(m.groupValues[1], ty, m.groupValues[3].trim()))
            }
            bcRe.matchEntire(t)?.let { m ->
                val params = parseParams(m.groupValues[2], s.src.path, ln, diags)
                bcs.add(BroadcastMeta(m.groupValues[1], params))
            }
            tickRe.matchEntire(t)?.let { m ->
                val n = m.groupValues[1].toInt()
                if (n !in 1..240) diags.add(Diag(s.src.path, ln, "onTick needs 1 to 240 ticks per second"))
                else if (n in ticks) diags.add(Diag(s.src.path, ln, "onTick($n) is declared twice"))
                else ticks.add(n)
            }
            everyRe.matchEntire(t)?.let { m ->
                val ms = Math.round(m.groupValues[1].toDouble() * 1000).toInt()
                if (ms < 1) diags.add(Diag(s.src.path, ln, "onEvery needs at least 0.001 seconds"))
                else if (ms in every) diags.add(Diag(s.src.path, ln, "onEvery(${m.groupValues[1]}) is declared twice"))
                else every.add(ms)
            }
            if (frameRe.matches(t)) frame = true
            barRe.matchEntire(t)?.let { m ->
                val path = m.groupValues[2].replace("^", "..")
                if (m.groupValues[1] == "empty") barEmpty = path else barFull = path
            }
            if (t.startsWith("fn onCreation")) diags.add(Diag(s.src.path, ln, "scripts cannot define onCreation: use onReady()"))
        }
        return Info(ScriptMeta(s.name, s.base, s.src.path, tweaks, ticks, every, frame, bcs, barEmpty, barFull), methodParams)
    }

    private fun inferKind(v: String): String {
        val t = v.trim()
        return when { t == "true" || t == "false" -> "Bool"; t.startsWith("\"") || t.startsWith("f\"") -> "String"
            t.toIntOrNull() != null -> "Int"; t.toDoubleOrNull() != null -> "Float"; else -> "Float" }
    }

    private fun parseParams(text: String, file: String, ln: Int, diags: MutableList<Diag>): List<Pair<String, String>> {
        if (text.isBlank()) return emptyList()
        return text.split(',').map { p ->
            val parts = p.split(':').map { it.trim() }
            if (parts.size != 2 || parts[0].isEmpty() || parts[1].isEmpty()) {
                diags.add(Diag(file, ln, "broadcast parameters need types: name: Type")); "x" to "Int"
            } else parts[0] to parts[1]
        }
    }

    // ---------------------------------------------------------------- lookups
    private fun userChain(name: String, metas: Map<String, ScriptMeta>): List<ScriptMeta> {
        val out = ArrayList<ScriptMeta>(); var m = metas[name]
        while (m != null && out.size < 64) { out.add(m); m = metas[m.base] }
        return out
    }

    /** Parameter types of broadcast [bc] on [type] (a script or node type), or null if it has none by that name. */
    private fun bcTypes(type: String, bc: String, metas: Map<String, ScriptMeta>): List<String>? {
        for (m in userChain(type, metas)) m.broadcasts.firstOrNull { it.name == bc }?.let { return it.params.map { p -> p.second } }
        val builtin = userChain(type, metas).lastOrNull()?.base ?: type
        return NodeTypes.broadcastsOf(builtin).firstOrNull { it.name == bc }?.types
    }
    /** Number of arguments of broadcast [bc] on [type], or -1. */
    private fun arity(type: String, bc: String, metas: Map<String, ScriptMeta>) = bcTypes(type, bc, metas)?.size ?: -1

    /** The one script or built-in type that declares broadcast [bc]; throws if there is none or several. */
    private fun ownerOf(bc: String, metas: Map<String, ScriptMeta>): String {
        val found = (metas.values.filter { m -> m.broadcasts.any { it.name == bc } }.map { it.name } +
            NodeTypes.all.filter { t -> t.broadcasts.any { it.name == bc } }.map { it.name }).distinct()
        return when (found.size) {
            0 -> throw LowerError("no node type has a broadcast called '$bc'")
            1 -> found[0]
            else -> throw LowerError("'$bc' exists on ${found.joinToString(", ")}: say which, for example fn onHear(@Path as ${found[0]}.$bc, ...)")
        }
    }

    private fun qualify(t: String) = if (t in NodeTypes.scriptClassNames) "nebula.$t" else t
    private fun baseRef(b: String, metas: Map<String, ScriptMeta>) = if (b in metas) b else "nebula.$b"

    // ---------------------------------------------------------------- emitting
    private fun emit(s: Script, info: Info, metas: Map<String, ScriptMeta>, out: Out, diags: MutableList<Diag>) {
        val file = s.src.path; val meta = info.meta
        // broadcast classes
        for (bc in meta.broadcasts) {
            val types = bc.params.joinToString(", ") { qualify(it.second) }
            val sig = bc.params.joinToString(", ") { "${it.first}: ${qualify(it.second)}" }
            val args = bc.params.joinToString(", ") { it.first }
            val cls = "_Bc_${s.name}_${bc.name}"
            out.add("class $cls:", file, s.headerLine)
            out.add("\tvar handlers: List[Fn($types)] = []"); out.add("\tvar owners: List[Int] = []")
            out.add("\tfn connect(handler: Fn($types), owner: Int):"); out.add("\t\thandlers.add(handler)"); out.add("\t\towners.add(owner)")
            out.add("\tfn send($sig):"); out.add("\t\tfor i in 1..handlers.length():")
            out.add("\t\t\tif nebula.nb_alive(owners[i]):"); out.add("\t\t\t\thandlers[i]($args)")
        }
        out.add("var _reg_${s.name}: Dict[Int, ${s.name}] = {}", file, s.headerLine)
        out.add("class ${s.name} extends ${baseRef(s.base, metas)}:", file, s.headerLine)
        val hearKeys = HashSet<String>(); val connects = ArrayList<Pair<Int, String>>()
        val deferred = deferFieldStarts(s, metas, diags)

        // generated constructor: registers the object, loads tweak overrides and sets the variables whose starting value uses other variables
        // (in the order they are written, so each one sees the tweaks and variables above it)
        out.add("\tfn onCreation(id: Int):")
        out.add("\t\tsuper.onCreation(id)")
        out.add("\t\t_reg_${s.name}[id] = self")
        for ((ln, raw) in s.body) {
            deferred[ln]?.let { d -> out.add("\t\t${d.name} = ${d.value}", file, ln) }
            val tm = tweakRe.matchEntire(stripComment(raw).trim()) ?: continue
            val t = meta.tweaks.firstOrNull { it.name == tm.groupValues[1] } ?: continue
            val getter = when (t.kind) { "Int" -> "int(nebula.nb_get_f(id, \"tweak:${t.name}\"))"; "Float" -> "nebula.nb_get_f(id, \"tweak:${t.name}\")"
                "Bool" -> "nebula.nb_get_b(id, \"tweak:${t.name}\")"; else -> "nebula.nb_get_s(id, \"tweak:${t.name}\")" }
            out.add("\t\tif nebula.nb_has(id, \"tweak:${t.name}\"):"); out.add("\t\t\t${t.name} = $getter")
        }

        for ((ln, raw) in s.body) {
            val indent = raw.takeWhile { it == '\t' || it == ' ' }
            val code = raw.substring(indent.length)
            val trimmed = stripComment(code).trim()
            val comment = commentStart(code).let { if (it >= 0) "  " + code.substring(it) else "" }
            fun add(text: String) = out.add(indent + text + comment, file, ln)
            if (trimmed.isEmpty()) { out.add(raw, file, ln); continue }
            val late = deferred[ln]
            if (late != null) { add("var ${late.name}: ${late.type} = ${late.start}"); continue }     // the real value is set in the constructor
            try {
                if (barRe.matches(trimmed)) {       // read by scan(); the engine and renderer use the metadata, so nothing is emitted
                    val base = userChain(s.name, metas).lastOrNull()?.base ?: s.name
                    if (!NodeTypes.isA(base, "DynamicBar")) throw LowerError("'empty @Node' and 'full @Node' only work in a script of DynamicBar")
                    if (indent != "\t") throw LowerError("write '${trimmed.substringBefore(' ')} @Node' at the top of the script, one tab in (not inside a function)")
                    add("# $trimmed"); continue
                }
                tweakRe.matchEntire(trimmed)?.let { m ->
                    val ann = m.groupValues[2]
                    add("var ${m.groupValues[1]}${if (ann.isNotEmpty()) ": $ann" else ""} = ${expr(m.groupValues[3], s, metas)}"); return@let
                } ?: bcRe.matchEntire(trimmed)?.let { m ->
                    add("var ${m.groupValues[1]} = _Bc_${s.name}_${m.groupValues[1]}()")
                } ?: tickRe.matchEntire(trimmed)?.let { m -> add("fn nbTick_${m.groupValues[1]}(delta: Float):")
                } ?: everyRe.matchEntire(trimmed)?.let { m ->
                    add("fn nbEvery_${Math.round(m.groupValues[1].toDouble() * 1000)}(delta: Float):")
                } ?: frameRe.matchEntire(trimmed)?.let { m -> add("fn onFrame(${m.groupValues[1].ifEmpty { "delta" }}: Float):")
                } ?: onHearRe.matchEntire(trimmed)?.let { m ->
                    add(onHear(m.groupValues[1], s, metas, hearKeys) { connects.add(ln to it) })
                } ?: run {
                    when {
                        trimmed.startsWith("shout ") -> {
                            val m = Regex("""^shout\s+([A-Za-z_]\w*)\s*(?:\((.*)\))?\s*$""").matchEntire(trimmed)
                            if (m == null) throw LowerError("expected: shout name(args)")
                            if (arity(s.name, m.groupValues[1], metas) < 0) throw LowerError("'${m.groupValues[1]}' is not a broadcast of ${s.name}")
                            val args = m.groupValues[2]
                            add("${m.groupValues[1]}.send(${if (args.isBlank()) "" else expr(args, s, metas)})")
                        }
                        trimmed.startsWith("hear ") -> throw LowerError("'hear' was replaced: write fn onHear(@Node.broadcast, params): ... (or fn onHear(broadcast, params): for your own)")
                        trimmed.startsWith("wait ") -> add("await sleep(${expr(trimmed.removePrefix("wait ").trim(), s, metas)})")
                        trimmed.startsWith("fn ") || trimmed.startsWith("async fn ") -> add(expr(trimmed, s, metas))
                        else -> add(expr(trimmed, s, metas))
                    }
                }
            } catch (e: LowerError) { diags.add(Diag(file, ln, e.message ?: "error")); out.add(raw, file, ln) }
        }

        if (connects.isNotEmpty()) {
            out.add("\tfn nbConnect():"); out.add("\t\tsuper.nbConnect()")
            for ((ln, c) in connects) out.add("\t\t$c", file, ln)
        }
        if (meta.ticks.isNotEmpty()) {
            out.add("\tfn nbTickDispatch(rate: Int, delta: Float):"); out.add("\t\tmatch rate:")
            for (n in meta.ticks) { out.add("\t\t\tcase $n:"); out.add("\t\t\t\tnbTick_$n(delta)") }
            out.add("\t\t\tdefault:"); out.add("\t\t\t\tsuper.nbTickDispatch(rate, delta)")
        }
        if (meta.everyMs.isNotEmpty()) {
            out.add("\tfn nbEveryDispatch(ms: Int, delta: Float):"); out.add("\t\tmatch ms:")
            for (n in meta.everyMs) { out.add("\t\t\tcase $n:"); out.add("\t\t\t\tnbEvery_$n(delta)") }
            out.add("\t\t\tdefault:"); out.add("\t\t\t\tsuper.nbEveryDispatch(ms, delta)")
        }
        out.add("fn _cast_${s.name}(n: nebula.Node) -> ${s.name}:")
        out.add("\tvar r = _reg_${s.name}.get(n.id)"); out.add("\tif r == null:")
        out.add("\t\tthrow f\"node '{n.name()}' is not a ${s.name}\""); out.add("\treturn r")
        for ((ln, raw) in s.extras) {
            try { out.add(if (raw.isBlank()) raw else expr(raw, s, metas, extra = true), file, ln) }
            catch (e: LowerError) { diags.add(Diag(file, ln, e.message ?: "error")); out.add(raw, file, ln) }
        }
    }

    private class LowerError(m: String) : Exception(m)

    // ---------------------------------------------------------------- script variables that start from other variables
    /** A script variable whose starting value is set in the constructor ([value], already lowered) because the compiler cannot evaluate it where the variable is declared. */
    private class Deferred(val name: String, val type: String, val value: String) {
        val start get() = when (type) { "Int" -> "0"; "Float" -> "0.0"; "Bool" -> "false"; else -> "\"\"" }
    }

    private val fieldRe = Regex("""^(var|const)\s+([A-Za-z_]\w*)\s*(?::\s*([A-Za-z_]\w*))?\s*=\s*(.+)$""")
    private val identRe = Regex("""(?<![\w.])[A-Za-z_]\w*""")
    private val basicTypes = setOf("Int", "Float", "Bool", "String")

    private fun literalKind(v: String): String? {
        val t = v.trim()
        return when { t == "true" || t == "false" -> "Bool"; t.startsWith("\"") || t.startsWith("f\"") -> "String"
            t.toIntOrNull() != null -> "Int"; t.toDoubleOrNull() != null -> "Float"; else -> null }
    }

    /** The code of [init] without string contents, except what sits inside the braces of an f-string (that is code too). */
    private fun codeOf(init: String): String {
        val sb = StringBuilder(); var i = 0
        while (i < init.length) {
            val c = init[i]
            if (c == '"') {
                var j = i + 1
                while (j < init.length && init[j] != '"') { if (init[j] == '\\') j++; j++ }
                val lit = init.substring(i + 1, minOf(j, init.length))
                if (i > 0 && init[i - 1] == 'f') {
                    sb.setLength(sb.length - 1)
                    for (m in Regex("""\{([^{}]+)\}""").findAll(lit)) sb.append(' ').append(m.groupValues[1]).append(' ')
                }
                sb.append(" \"\" "); i = j + 1
            } else { sb.append(c); i++ }
        }
        return sb.toString()
    }

    /** Type of plain arithmetic over typed variables and numbers ("speed * 2" is Float when speed is), or null when it needs a type written by hand. */
    private fun arithmeticKind(code: String, kinds: Map<String, String?>): String? {
        val t = code.trim()
        if (Regex("""[A-Za-z_]\w*""").matches(t)) return kinds[t]?.takeIf { it in basicTypes }
        if (!Regex("""[\w\s+\-*%().]+""").matches(t)) return null
        var float = false
        for (m in Regex("""[A-Za-z_]\w*|\d+(?:\.\d+)?""").findAll(t)) {
            val tok = m.value
            if (tok[0].isDigit()) { if ('.' in tok) float = true }
            else when (kinds[tok]) { "Float" -> float = true; "Int" -> {}; else -> return null }
        }
        return if (float) "Float" else "Int"
    }

    /**
     * SuperNova evaluates a field's starting value where the field is declared, with no access to the other fields or to `id`.
     * So `var run = speed * 2` (or `var hp = maxHp`) would fail with "undefined variable 'speed'". Such variables are declared with a plain
     * starting value and set in the generated constructor instead; the result maps script line -> variable. Values that cannot be moved there
     * (a node path, spawn, a type that is not plain to see) get a clear message instead of a compiler error.
     */
    private fun deferFieldStarts(s: Script, metas: Map<String, ScriptMeta>, diags: MutableList<Diag>): Map<Int, Deferred> {
        val file = s.src.path
        val indent = s.body.firstOrNull { stripComment(it.second).isNotBlank() }?.second?.takeWhile { it == '\t' || it == ' ' } ?: return emptyMap()
        val kinds = HashMap<String, String?>()
        for (m in userChain(s.name, metas)) for (t in m.tweaks) kinds[t.name] = t.kind
        val fields = ArrayList<Pair<Int, String>>()
        for ((ln, raw) in s.body) {
            if (!raw.startsWith(indent) || raw.length > indent.length && raw[indent.length].isWhitespace()) continue      // only this level: not the lines inside a function
            val t = stripComment(raw).trim()
            fieldRe.matchEntire(t)?.let { m -> kinds[m.groupValues[2]] = m.groupValues[3].ifEmpty { literalKind(m.groupValues[4]) }; fields.add(ln to t) }
            if (tweakRe.matches(t)) fields.add(ln to t)
        }
        val out = HashMap<Int, Deferred>()
        for ((ln, t) in fields) {
            val tm = tweakRe.matchEntire(t); val fm = if (tm == null) fieldRe.matchEntire(t) else null
            val name = tm?.groupValues?.get(1) ?: fm?.groupValues?.get(2) ?: continue
            val init = (tm?.groupValues?.get(3) ?: fm?.groupValues?.get(4) ?: continue).trim()
            val code = codeOf(init)
            val needsNode = '@' in code || Regex("""\bspawn\b""").containsMatchIn(code)
            val refs = identRe.findAll(code).map { it.value }.filter { it != name && it in kinds }.distinct().toList()
            if (refs.isEmpty() && !needsNode) continue
            if (needsNode) {
                diags.add(Diag(file, ln, "'$name' cannot start as a node (@Path) or a spawn: nodes do not exist yet while the script is created. " +
                    "Use a small function instead, for example: fn $name() -> Node: return @Path")); continue
            }
            if (fm != null && fm.groupValues[1] == "const") {
                diags.add(Diag(file, ln, "'$name' is a const and cannot start from the variable ${refs.first()}: use var, or write the number here")); continue
            }
            val type = if (tm != null) kinds[name] else fm!!.groupValues[3].ifEmpty { literalKind(init) ?: arithmeticKind(code, kinds) ?: "" }
            if (type == null || type !in basicTypes) {
                val typed = fm != null && fm.groupValues[3].isNotEmpty()
                diags.add(Diag(file, ln, if (typed) "'$name' cannot start from the variable ${refs.first()}: only Int, Float, Bool and String variables can. Set it inside fn onReady() instead"
                    else "'$name' starts from the variable ${refs.first()}: write its type so it can be set when the script is created, for example: var $name: Float = $init")); continue
            }
            try { out[ln] = Deferred(name, type, expr(init, s, metas)) }
            catch (e: LowerError) { diags.add(Diag(file, ln, e.message ?: "error")); continue }
            kinds[name] = type
        }
        return out
    }

    private val onHearRe = Regex("""^fn\s+onHear\s*\((.*)\)\s*:\s*$""")
    private val hearSrcRe = Regex("""^(@([\w/^]*)(?:\s+as\s+([A-Za-z_]\w*))?\s*\.\s*)?([A-Za-z_]\w*)$""")

    /**
     * `fn onHear(@Path.bc, a, b):` listens to broadcast `bc` of the node at `@Path`; `fn onHear(bc, a):` to the script's own.
     * The values are matched by position; the handler may list fewer names than the broadcast sends.
     * Lowers the header to a typed method and hands the connect statement (run just before onReady) to [connect].
     */
    private fun onHear(inner: String, s: Script, metas: Map<String, ScriptMeta>, seen: MutableSet<String>, connect: (String) -> Unit): String {
        val parts = inner.split(',').map { it.trim() }
        val m = hearSrcRe.matchEntire(parts[0])
            ?: throw LowerError("expected: fn onHear(@Node.broadcast, param, ...):   or   fn onHear(broadcast, param, ...):")
        val fromNode = m.groupValues[1].isNotEmpty(); val path = m.groupValues[2]; val bc = m.groupValues[4]
        if (fromNode && path.isEmpty()) throw LowerError("'@' needs a node path, for example @Enemy or @^/Sibling")
        val type = if (!fromNode) s.name else m.groupValues[3].ifEmpty { ownerOf(bc, metas) }
        val types = bcTypes(type, bc, metas) ?: throw LowerError("'$type' has no broadcast '$bc'")
        val names = parts.drop(1)
        for (p in names) if (!Regex("""[A-Za-z_]\w*""").matches(p)) throw LowerError("'$p' is not a parameter name")
        if (names.size > types.size) throw LowerError("'$bc' sends ${types.size} value(s) but onHear names ${names.size}")
        if (!seen.add((if (fromNode) "@$path" else "") + "." + bc)) throw LowerError("onHear for '${parts[0]}' is declared twice")
        val fn = "nbHear_${s.name}_${seen.size}_$bc"
        val target = if (fromNode) cast(type, nodePath(path), metas) + "." else ""
        val lam = types.indices.joinToString(", ") { "a${it + 1}" }
        val used = names.indices.joinToString(", ") { "a${it + 1}" }
        connect("$target$bc.connect(fn($lam) => $fn($used), id)")
        return "fn $fn(" + names.mapIndexed { i, p -> "$p: ${qualify(types[i])}" }.joinToString(", ") + "):"
    }

    private fun cast(type: String, e: String, metas: Map<String, ScriptMeta>): String = when {
        type == "Node" -> e
        type in metas -> "_cast_$type($e)"
        NodeTypes.exists(type) -> "nebula.as$type($e)"
        else -> throw LowerError("unknown type '$type' in 'as $type'")
    }

    // ---------------------------------------------------------------- expressions
    private val spawnRe = Regex("""\bspawn\s+(\u0001\d+\u0001|[A-Za-z_]\w*)\s+under\s+(@[\w/^]*|[A-Za-z_]\w*)(?:\s+as\s+([A-Za-z_]\w*))?""")
    private val nodeRe = Regex("""@([\w/^]*)(?:\s+as\s+([A-Za-z_]\w*))?""")
    private val typeWordRe = Regex("""(?<![\w.])(${NodeTypes.scriptClassNames.joinToString("|")})(?![\w])""")

    /** Lowers one line of code: node paths, spawn, casts, built-in class names. */
    private fun expr(line: String, s: Script, metas: Map<String, ScriptMeta>, extra: Boolean = false): String {
        val commentAt = commentStart(line)
        val comment = if (commentAt >= 0) line.substring(commentAt) else ""
        val codePart = if (commentAt >= 0) line.substring(0, commentAt) else line
        // mask strings; f-string {expressions} are lowered recursively
        val strs = ArrayList<String>(); val sb = StringBuilder(); var i = 0
        while (i < codePart.length) {
            val c = codePart[i]
            if (c == '"') {
                var j = i + 1
                while (j < codePart.length && codePart[j] != '"') { if (codePart[j] == '\\') j++; j++ }
                var lit = codePart.substring(i, minOf(j + 1, codePart.length))
                val isF = i > 0 && codePart[i - 1] == 'f' && (i < 2 || !(codePart[i - 2].isLetterOrDigit() || codePart[i - 2] == '_'))
                if (isF) lit = Regex("""\{([^{}]+)\}""").replace(lit) { m -> "{" + expr(m.groupValues[1], s, metas, extra) + "}" }
                strs.add(lit); sb.append('\u0001').append(strs.size - 1).append('\u0001'); i = j + 1
            } else { sb.append(c); i++ }
        }
        var code = sb.toString()
        if (!extra) {
            code = spawnRe.replace(code) { m ->
                val parent = if (m.groupValues[2].startsWith("@")) nodePath(m.groupValues[2].substring(1)) else m.groupValues[2]
                val call = "nebula.spawn(${m.groupValues[1]}, $parent)"
                if (m.groupValues[3].isNotEmpty()) cast(m.groupValues[3], call, metas) else call
            }
            code = nodeRe.replace(code) { m ->
                if (m.value.startsWith("@") && m.groupValues[1].isEmpty() && m.groupValues[2].isEmpty()) throw LowerError("'@' needs a node path, for example @Player or @^/Sibling")
                val node = nodePath(m.groupValues[1])
                if (m.groupValues[2].isNotEmpty()) cast(m.groupValues[2], node, metas) else node
            }
        }
        code = typeWordRe.replace(code) { "nebula." + it.value }
        code = Regex("""\u0001(\d+)\u0001""").replace(code) { strs[it.groupValues[1].toInt()] }
        return code + (if (comment.isNotEmpty()) "  $comment" else "")
    }

    private fun nodePath(p: String): String {
        val path = p.replace("^", "..")
        return "nebula.nodeAt(id, \"$path\")"
    }
